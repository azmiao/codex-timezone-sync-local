#!/usr/bin/env python3
"""Embed the self-contained management panel into the native plugin.

The panel is a single HTML file with inline CSS and JS, so the plugin serves it
without any external asset, CDN or build step.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / 'dashboard.html'
TARGET = ROOT / 'dashboard_bundle.h'
PER_LINE = 20


def main():
    raw = SOURCE.read_bytes()
    numbers = [str(byte) for byte in raw]
    rows = '\n'.join(
        '  ' + ', '.join(numbers[i:i + PER_LINE]) + ','
        for i in range(0, len(numbers), PER_LINE)
    )
    TARGET.write_text(
        '/* Auto-generated by embed_ui.py; do not edit. */\n'
        f'/* Source: dashboard.html ({len(raw)} bytes) */\n'
        'static const unsigned char dashboard_html[] = {\n'
        f'{rows}\n'
        '};\n'
        'static const size_t dashboard_html_size = sizeof(dashboard_html);\n',
        encoding='ascii',
        newline='\n',
    )
    print(f'embedded {SOURCE.name}: {len(raw)} bytes')


if __name__ == '__main__':
    main()
